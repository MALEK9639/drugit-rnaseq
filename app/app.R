library(shiny)
library(bslib)
library(DT)
library(plotly)
library(ggplot2)

# ------------------------------------------------------------------ data
res  <- readRDS("data/results.rds")
meta <- readRDS("data/metadata.rds")
expr <- readRDS("data/expression_vst.rds")
pca  <- readRDS("data/pca.rds")
enr  <- readRDS("data/enrichment.rds")
prm  <- readRDS("data/params.rds")

meta <- meta[match(colnames(expr), meta$sample_id), ]

up_lab   <- paste("Up in", prm$group_test)
down_lab <- paste("Down in", prm$group_test)
ns_lab   <- "Not significant"
status_cols <- setNames(c("#D55E00", "#0072B2", "grey70"), c(up_lab, down_lab, ns_lab))
grp_cols    <- setNames(c("#0072B2", "#D55E00"), c(prm$group_ref, prm$group_test))

gene_choices <- sort(unique(res$label))
default_gene <- if ("BEST4" %in% gene_choices) "BEST4" else gene_choices[1]
pc_choices   <- names(pca$var)

