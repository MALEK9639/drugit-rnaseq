# ------------------------------------------------------------------ server
server <- function(input, output, session) {

  # ---- PCA
  output$pca_plot <- renderPlotly({
    sc <- pca$scores
    sc$x <- sc[[input$pcx]]
    sc$y <- sc[[input$pcy]]
    sc$hover <- paste0("Patient ", sc$patient, " (", sc$group, ")")
    p <- plot_ly()
    if (isTRUE(input$link_pairs)) {
      a <- sc[sc$group == prm$group_ref, c("patient", "x", "y")]
      b <- sc[sc$group == prm$group_test, c("patient", "x", "y")]
      w <- merge(a, b, by = "patient", suffixes = c("_a", "_b"))
      p <- add_segments(p, data = w, x = ~x_a, xend = ~x_b, y = ~y_a, yend = ~y_b,
                        line = list(color = "lightgrey", width = 1),
                        showlegend = FALSE, hoverinfo = "skip", inherit = FALSE)
    }
    p <- add_markers(p, data = sc, x = ~x, y = ~y, color = ~group, colors = grp_cols,
                     symbol = ~group, symbols = c("circle", "triangle-up"),
                     text = ~hover, hoverinfo = "text", marker = list(size = 11))
    layout(p,
           xaxis = list(title = sprintf("%s (%.1f%%)", input$pcx, pca$var[[input$pcx]])),
           yaxis = list(title = sprintf("%s (%.1f%%)", input$pcy, pca$var[[input$pcy]])))
  })

  # ---- Volcano
  vol <- reactive({
    d <- res[!is.na(res$padj) & !is.na(res$log2FC_shrunk), ]
    sig <- d$padj < input$padj_cut & abs(d$log2FC_shrunk) >= input$lfc_cut
    d$status <- ifelse(sig & d$log2FC_shrunk > 0, up_lab,
                ifelse(sig & d$log2FC_shrunk < 0, down_lab, ns_lab))
    d$status <- factor(d$status, levels = c(up_lab, down_lab, ns_lab))
    d$nlp <- -log10(pmax(d$padj, 1e-300))
    d
  })

  output$vol_counts <- renderText({
    d <- vol()
    paste0("Tested genes: ", nrow(d),
           "\n", up_lab, ": ", sum(d$status == up_lab),
           "\n", down_lab, ": ", sum(d$status == down_lab))
  })

  output$volcano <- renderPlotly({
    d <- vol()
    d$hover <- paste0(d$label, "<br>log2FC: ", round(d$log2FC_shrunk, 2),
                      "<br>adj. p: ", signif(d$padj, 2))
    p <- plot_ly(d, x = ~log2FC_shrunk, y = ~nlp, color = ~status, colors = status_cols,
                 type = "scattergl", mode = "markers", text = ~hover, hoverinfo = "text",
                 marker = list(size = 4, opacity = 0.6))
    hl <- trimws(input$hl_gene)
    if (nzchar(hl)) {
      h <- d[toupper(d$label) == toupper(hl), ]
      if (nrow(h) > 0) {
        p <- add_trace(p, data = h, x = ~log2FC_shrunk, y = ~nlp, type = "scatter",
                       mode = "markers+text", text = ~label, textposition = "top center",
                       marker = list(size = 13, color = "rgba(0,0,0,0)",
                                     line = list(color = "black", width = 2)),
                       inherit = FALSE, showlegend = FALSE, hoverinfo = "skip")
      }
    }
    layout(p,
           xaxis = list(title = "log2 fold change (shrunken)"),
           yaxis = list(title = "-log10 adjusted p-value"),
           shapes = list(
             list(type = "line", x0 = input$lfc_cut, x1 = input$lfc_cut, y0 = 0, y1 = 1,
                  yref = "paper", line = list(dash = "dash", color = "grey")),
             list(type = "line", x0 = -input$lfc_cut, x1 = -input$lfc_cut, y0 = 0, y1 = 1,
                  yref = "paper", line = list(dash = "dash", color = "grey")),
             list(type = "line", x0 = 0, x1 = 1, xref = "paper",
                  y0 = -log10(input$padj_cut), y1 = -log10(input$padj_cut),
                  line = list(dash = "dash", color = "grey"))))
  })

  sig_df <- reactive({
    d <- vol()
    d <- d[d$status != ns_lab, ]
    d <- d[order(d$padj), c("label", "gene_name", "baseMean", "log2FC_shrunk", "padj", "status")]
    names(d) <- c("Gene", "Description", "Mean expression", "log2FC", "Adjusted p", "Direction")
    d$Direction <- as.character(d$Direction)
    d
  })

  output$sig_table <- renderDT({
    datatable(sig_df(), rownames = FALSE, options = list(pageLength = 10, scrollX = TRUE)) |>
      formatRound(c("Mean expression", "log2FC"), 2) |>
      formatSignif("Adjusted p", 3)
  })

  output$dl_sig <- downloadHandler(
    filename = function() "significant_genes.csv",
    content  = function(file) write.csv(sig_df(), file, row.names = FALSE)
  )

  # ---- Gene explorer
  updateSelectizeInput(session, "gene", choices = gene_choices,
                       selected = default_gene, server = TRUE)

  sel_idx <- reactive({
    req(input$gene)
    match(input$gene, res$label)
  })

  output$gene_stats <- renderUI({
    i <- sel_idx()
    req(!is.na(i))
    r <- res[i, ]
    tagList(
      if (nzchar(r$gene_name)) p(r$gene_name),
      tags$ul(
        tags$li("log2FC (shrunken): ", sprintf("%.2f", r$log2FC_shrunk)),
        tags$li("Adjusted p: ", format(r$padj, digits = 3, scientific = TRUE)),
        tags$li("Mean normalised count: ", round(r$baseMean, 1)),
        tags$li("Call (default thresholds): ", r$direction)
      )
    )
  })

  output$gene_plot <- renderPlot({
    i <- sel_idx()
    req(!is.na(i))
    gid <- res$gene_id[i]
    validate(need(gid %in% rownames(expr), "Expression values are not available for this gene."))
    d <- data.frame(sample_id = colnames(expr), value = as.numeric(expr[gid, ]),
                    tissue = meta$group, patient = meta$patient)
    ggplot(d, aes(tissue, value)) +
      geom_line(aes(group = patient), colour = "grey70") +
      geom_point(aes(colour = tissue), size = 3) +
      scale_colour_manual(values = grp_cols) +
      labs(x = NULL, y = "Expression (VST, log2 scale)", colour = NULL,
           title = paste0(input$gene, ": each line is one patient")) +
      theme_minimal(base_size = 14)
  })

  # ---- Enrichment
  enr_data <- reactive({
    d <- enr[[input$enr_set]]
    validate(need(!is.null(d) && nrow(d) > 0, "No significant term for this analysis."))
    d <- d[order(d$p.adjust), ]
    head(d, input$enr_n)
  })

  output$enr_plot <- renderPlot({
    d <- enr_data()
    d$Description <- factor(d$Description, levels = unique(rev(d$Description)))
    if (input$enr_set == "gsea") {
      g <- ggplot(d, aes(NES, Description, size = setSize, colour = -log10(p.adjust))) +
        labs(x = paste0("Normalised enrichment score (positive = higher in ", prm$group_test, ")"),
             size = "Gene set size")
    } else {
      g <- ggplot(d, aes(GeneRatioNum, Description, size = Count, colour = -log10(p.adjust))) +
        labs(x = "Gene ratio", size = "Genes")
    }
    g + geom_point() +
      scale_colour_viridis_c(option = "C", end = 0.9) +
      scale_y_discrete(labels = scales::label_wrap(45)) +
      labs(y = NULL, colour = "-log10 adj. p") +
      theme_minimal(base_size = 13)
  })

  output$enr_table <- renderDT({
    d <- enr_data()
    keep <- intersect(c("Description", "Count", "GeneRatio", "setSize", "NES",
                        "p.adjust", "geneID", "core_enrichment"), names(d))
    datatable(d[, keep, drop = FALSE], rownames = FALSE,
              options = list(pageLength = 8, scrollX = TRUE))
  })
}

shinyApp(ui, server)
